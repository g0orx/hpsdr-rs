//! The radio functions a control -- a MIDI control in hpsdr-rs, or a
//! front-panel encoder or switch in either program -- can be bound to.
//! Their names are what's saved (midi.json, controller.json), so they
//! mustn't be renamed.

use serde::{Deserialize, Serialize};

/// A radio function a MIDI control can be bound to. Deliberately a small
/// subset of piHPSDR's ~90 actions -- see the MIDI support plan for which
/// ones were left out for v1 and why (mostly: setup/calibration-time
/// controls like PureSignal/Diversity/Equalizer, and anything tied to a
/// per-receiver concept this app doesn't have).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum MidiAction {
    Mox,
    Tune,
    Split,
    SatMode,
    RitToggle,
    RitClear,
    XitToggle,
    XitClear,
    VfoAtoB,
    VfoBtoA,
    VfoSwap,
    ModeUp,
    ModeDown,
    BandUp,
    BandDown,
    FilterWidthUp,
    FilterWidthDown,
    VfoStepUp,
    VfoStepDown,
    NoiseBlankerCycle,
    NoiseReductionCycle,
    AfGain,
    AgcGain,
    MicGain,
    RfAttenuation,
    TxDrive,
    CwSpeed,
    FilterWidth,
    VfoTune,
    RitAdjust,
    XitAdjust,
    VfoBTune,
    CtunToggle,
    RxEqToggle,
    DiversityToggle,
    BinauralToggle,
    SnbToggle,
    Band160m,
    Band80m,
    Band40m,
    Band30m,
    Band20m,
    Band17m,
    Band15m,
    Band12m,
    Band10m,
    Band6m,
    NoiseBlankerOff,
    NoiseBlankerNb,
    NoiseBlankerNb2,
    NoiseReductionOff,
    NoiseReductionNr,
    NoiseReductionNr2,
    NoiseReductionNr3,
    /// A CW key: down while the note is held (issue #15, a keyer sending
    /// its key as MIDI). Handled on the MIDI thread itself -- see
    /// MidiCwKey -- not the frame loop, so keying timing doesn't wait on
    /// the UI.
    CwKey,
    CwSidetoneLevel,
    CwSidetoneFreq,
    CwPitch,
    /// The next entry of the current band's band stack, as pressing its
    /// band button again (piHPSDR's band stack button).
    BandStack,
    /// The VFO step (VFO-A's box) one larger / smaller -- piHPSDR's
    /// VFO_STEP_PLUS/MINUS. Not VfoStepUp/Down, which tune by a step.
    VfoStepSizeUp,
    VfoStepSizeDown,
}

